// Use the pinned route adapters without loading the package's HTTP server.

type Query = Record<string, string>;
type ApiModule = (query: Query, request: UpstreamRequest) => Promise<UpstreamAnswer>;

const checkQr: ApiModule = (query, request) =>
    request('/api/login/qrcode/client/login', { key: query.key, type: 3 }, { crypto: 'weapi' });

const songUrl: ApiModule = (query, request) => request('/api/song/enhance/player/url/v1', {
    ids: '[' + query.id + ']',
    level: query.level,
    encodeType: query.level === 'vivid' ? 'mp3' : 'flac',
    ...(query.level === 'sky' ? { immerseType: 'c51' } : {}),
}, { crypto: 'xeapi' });

const qrImage: ApiModule = async query => {
    const url = new URL('https://music.163.com/login');
    url.searchParams.set('codekey', query.key);
    const qrurl = url.toString();
    const qrimg = await QRCode.toDataURL(qrurl);
    return { status: 200, body: { code: 200, data: { qrurl, qrimg } }, cookie: [] };
};

const qrKey: ApiModule = (query, request) => login_qr_key({ ...query, crypto: 'weapi' }, request);

